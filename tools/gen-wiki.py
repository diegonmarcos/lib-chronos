#!/usr/bin/env python3
"""
gen-wiki — #1867 the Cloud Wiki dataset (wiki.json) generated from this repository's folder tree.

  gen-wiki.py            write wiki.json at the repo root from the tree
  gen-wiki.py --check    regenerate in memory; exit 1 when the committed wiki.json differs (the CI drift check)
  gen-wiki.py --menu     print the menu tree (parents > hubs > topics), the view the app's side menu is checked against
  gen-wiki.py --root D   read the tree under D instead of this repo (the tester runs it on scratch copies)

THE TREE IS THE STRUCTURE. A node is a folder named <number>.<Name> holding an index.md; its number is its parent's number plus one
segment (1.Modern-science > 1.0.Science > 1.0.0.Math > 1.0.0.0.Algebra). index.md starts with a front matter block:

  ---
  kind: parent | hub | topic | page | project | graph
  id: <unique id>            (a page id is <topic id>.<slug>)
  label: <menu name>         (a page has `title:` instead)
  icon: <libs:ui-icons name> (not on a page)
  tags: a, b, c              (a page: its tag chips)
  site: index.html           (a topic with an HTML site in its folder: Chronos)
  markdown: / explorer:      (a project: its Markdown page and its web page, files of its folder)
  ---
  <Markdown: a page's text, or the intro of any other node>

Nesting: parent > hub | topic | project; hub > topic | graph; topic > page. Any other folder inside a node is a site file of a topic
with `site` or of a project, and nothing else may hold one. Output order is the folders' natural order; no time, host or commit is
written, so the same tree always gives the same bytes. Python 3 stdlib only.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = "wiki.json"
NODE = re.compile(r"^(\d+(?:\.\d+)*)\.([A-Za-z].*)$")
CHILD = {"root": {"parent"}, "parent": {"hub", "topic", "project"}, "hub": {"topic", "graph"}, "topic": {"page"},
         "page": set(), "project": set(), "graph": set()}
KEYS = {"parent": {"kind", "id", "label", "icon"}, "hub": {"kind", "id", "label", "icon"},
        "topic": {"kind", "id", "label", "icon", "site"}, "page": {"kind", "id", "title", "tags"},
        "project": {"kind", "id", "label", "icon", "markdown", "explorer"}, "graph": {"kind", "id", "label", "icon"}}
NEED = {"parent": {"id", "label", "icon"}, "hub": {"id", "label", "icon"}, "topic": {"id", "label", "icon"},
        "page": {"id", "title", "tags"}, "project": {"id", "label", "icon", "markdown", "explorer"}, "graph": {"id", "label", "icon"}}
DOC = ("GENERATED by tools/gen-wiki.py from the folder tree of this repository (diegonmarcos/Projects-Library-KG). DO NOT EDIT: edit the "
       "index.md of a folder and re-run the tool. #1867 the content of Cloud Wiki: menu = the side menu (parents > hubs > topics), "
       "hubs = the parent and hub pages with their intros, topics[].pages = each topic's tabs (Markdown, tags, [[id]] links), "
       "projects = the project folders (Markdown page + web page). Cloud Wiki reads this file from its runtime clone of the repo.")


class Bad(Exception):
    pass


def natural(s):
    return [int(x) if x.isdigit() else x.lower() for x in re.split(r"(\d+)", s)]


def front(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if not text.startswith("---\n"):
        raise Bad("%s does not start with a front matter block (---)" % path)
    end = text.find("\n---\n", 4)
    if end < 0:
        raise Bad("%s: the front matter block is not closed" % path)
    meta = {}
    for line in text[4:end].split("\n"):
        if not line.strip():
            continue
        k, sep, v = line.partition(":")
        if not sep:
            raise Bad("%s: front matter line %r is not key: value" % (path, line))
        k = k.strip()
        if k in meta:
            raise Bad("%s: front matter key %s twice" % (path, k))
        meta[k] = v.strip()
    body = text[end + 5:]
    if body.endswith("\n"):
        body = body[:-1]
    return meta, body


def build(root):
    seen = {}
    menu, hubs, topics, projects = [], [], [], []

    def rel(d):
        return os.path.relpath(d, root).replace(os.sep, "/")

    def node(d, kind_up, num_up, topic=None):
        """The child nodes of folder d (whose kind is kind_up and number num_up), as menu entries."""
        out = []
        siteful = False
        for n in sorted(os.listdir(d), key=natural):
            p = os.path.join(d, n)
            if n.startswith(".") or not os.path.isdir(p):
                continue
            m = NODE.match(n)
            md = os.path.join(p, "index.md")
            want = (num_up + "." if num_up else "")
            if not (m and os.path.isfile(md) and m.group(1).startswith(want) and m.group(1).count(".") == (num_up.count(".") + 1 if num_up else 0)
                    and m.group(1)[len(want):].isdigit()):
                if os.path.isfile(md):
                    raise Bad("%s holds an index.md but is not numbered as a child of %s (%s.<n>.<Name>)" % (rel(p), rel(d) or ".", num_up or "<n>"))
                if kind_up in ("topic", "project") and site_ok(d):
                    siteful = True
                    continue
                if kind_up == "root":
                    continue  # the repo's own files: tools/, the Library board
                raise Bad("%s has no index.md: a folder inside %s is a page, or a site file of a topic with `site` or of a project" % (rel(p), rel(d)))
            meta, body = front(md)
            kind = meta.get("kind", "")
            if kind not in CHILD.get(kind_up, set()):
                raise Bad("%s is a %r inside a %s; allowed: %s" % (rel(md), kind, kind_up, sorted(CHILD.get(kind_up, set()))))
            extra = set(meta) - KEYS[kind]
            if extra:
                raise Bad("%s: unknown front matter keys %s" % (rel(md), sorted(extra)))
            miss = sorted(k for k in NEED[kind] if not meta.get(k))
            if miss:
                raise Bad("%s: missing %s" % (rel(md), miss))
            nid = meta["id"]
            if nid in seen:
                raise Bad("id %s is used by %s and %s" % (nid, seen[nid], rel(p)))
            seen[nid] = rel(p)
            path = rel(p)
            if kind == "page":
                if not nid.startswith(topic["id"] + "."):
                    raise Bad("page %s is not prefixed by its topic %s" % (nid, topic["id"]))
                tags = [t.strip() for t in meta["tags"].split(",") if t.strip()]
                topic["pages"].append({"id": nid, "title": meta["title"], "tags": tags, "md": body, "path": path})
                node(p, "page", m.group(1), topic)
                continue
            entry = {"id": nid, "label": meta["label"], "icon": meta["icon"], "kind": kind, "path": path}
            if kind in ("parent", "hub"):
                kids = node(p, kind, m.group(1))
                entry["children"] = kids
                hubs.append({"id": nid, "label": meta["label"], "icon": meta["icon"], "kind": kind, "path": path, "intro": body,
                             "children": [k["id"] for k in kids]})
            elif kind == "topic":
                t = {"id": nid, "label": meta["label"], "intro": body, "pages": [], "icon": meta["icon"], "path": path}
                if meta.get("site"):
                    if not os.path.isfile(os.path.join(p, meta["site"])):
                        raise Bad("%s: site %s is not in the folder" % (rel(md), meta["site"]))
                    t["site"] = meta["site"]
                    entry["site"] = meta["site"]
                topics.append(t)
                node(p, "topic", m.group(1), t)
            elif kind == "project":
                for k in ("markdown", "explorer"):
                    if not os.path.isfile(os.path.join(p, meta[k])):
                        raise Bad("%s: %s %s is not in the folder" % (rel(md), k, meta[k]))
                projects.append({"id": nid, "label": meta["label"], "icon": meta["icon"], "path": path, "intro": body,
                                 "markdown": meta["markdown"], "explorer": meta["explorer"]})
                entry["markdown"], entry["explorer"] = meta["markdown"], meta["explorer"]
                node(p, "project", m.group(1))
            elif kind == "graph":
                node(p, "graph", m.group(1))
            out.append(entry)
        return out

    def site_ok(d):
        md = os.path.join(d, "index.md")
        if not os.path.isfile(md):
            return False
        meta, _ = front(md)
        return meta.get("kind") == "project" or bool(meta.get("site"))

    menu = node(root, "root", "")
    if not menu:
        raise Bad("no numbered folder with an index.md at the root")
    ids = {p["id"] for t in topics for p in t["pages"]}
    for t in topics:
        for text in [t["intro"]] + [p["md"] for p in t["pages"]]:
            for l in re.findall(r"\[\[([^\]\s]+)\]\]", text):
                if l not in ids:
                    raise Bad("a page of topic %s links to unknown page %s" % (t["id"], l))
    for h in hubs + projects:
        for l in re.findall(r"\[\[([^\]\s]+)\]\]", h["intro"]):
            if l not in ids:
                raise Bad("the intro of %s links to unknown page %s" % (h["id"], l))
    return {"schemaVersion": 2, "_doc": DOC, "menu": menu, "hubs": hubs, "topics": topics, "projects": projects}


def render(root):
    return json.dumps(build(root), indent=1, ensure_ascii=False) + "\n"


def main(argv):
    root = ROOT
    if "--root" in argv:
        i = argv.index("--root")
        root = os.path.abspath(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
    try:
        text = render(root)
    except Bad as e:
        print("gen-wiki: " + str(e), file=sys.stderr)
        return 1
    out = os.path.join(root, OUT)
    if argv[:1] == ["--check"]:
        have = open(out, encoding="utf-8").read() if os.path.isfile(out) else ""
        if have != text:
            print("gen-wiki: %s is not what the tree generates; run tools/gen-wiki.py (never edit it by hand)" % OUT, file=sys.stderr)
            return 1
        print("gen-wiki --check: %s equals the tree" % OUT)
        return 0
    if argv[:1] == ["--menu"]:
        def show(ms, depth):
            for m in ms:
                print("  " * depth + "%s %s (%s)" % (m["kind"], m["id"], m["label"]))
                show(m.get("children", []), depth + 1)
        show(json.loads(text)["menu"], 0)
        return 0
    if argv:
        print("gen-wiki: unknown arguments %s" % argv, file=sys.stderr)
        return 1
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    d = json.loads(text)
    print("gen-wiki: %s, %d topics, %d pages, %d hubs, %d projects" % (OUT, len(d["topics"]), sum(len(t["pages"]) for t in d["topics"]), len(d["hubs"]), len(d["projects"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
